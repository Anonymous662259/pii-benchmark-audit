"""NER dataset registry for fine-tuning GLiNER2 on standard NER benchmarks.

Each entry provides the HuggingFace repo, native label descriptions, train split,
and val/test split candidates (each tried in order, first available wins).

Used by:
  - training/train.py  (--ner-dataset flag)
  - evaluation/evaluate.py (--ner-dataset flag)
  - scripts/run_ner_datasets.py (replaces the old inline _DATASETS dict)
"""

from typing import Dict, Iterable, List, Optional


def load_desc_override(path: str, registry_descriptions: Dict[str, str]) -> Dict[str, str]:
    """Load a {label: description} JSON override and validate it against the
    dataset registry: keys must cover the SAME label set (case-insensitive) —
    a typo'd or missing label silently zeroing a class is the failure mode
    this guard exists for. Returns the override with the REGISTRY's casing so
    downstream case handling (and training gold alignment) is unchanged.

    Shared by training/train.py and evaluation/evaluate.py (--desc-file), so a
    model can be TRAINED and EVALUATED on the exact same rich schema.
    """
    import json as _json
    with open(path, "r", encoding="utf-8") as f:
        override = _json.load(f)
    if not isinstance(override, dict) or not all(
        isinstance(k, str) and isinstance(v, str) for k, v in override.items()
    ):
        raise SystemExit(f"--desc-file {path}: expected a flat {{label: description}} JSON object")
    reg_by_upper = {k.upper(): k for k in registry_descriptions}
    ovr_by_upper = {k.upper(): v for k, v in override.items()}
    missing = sorted(set(reg_by_upper) - set(ovr_by_upper))
    extra = sorted(set(ovr_by_upper) - set(reg_by_upper))
    if missing or extra:
        raise SystemExit(
            f"--desc-file {path}: label set mismatch vs registry — "
            f"missing={missing or 'none'} extra={extra or 'none'}"
        )
    return {reg_key: ovr_by_upper[up] for up, reg_key in reg_by_upper.items()}


def resolve_split(available: Iterable[str], candidates: List[str]) -> Optional[str]:
    """Return the first of `candidates` present in `available`, or None."""
    avail = set(available)
    for s in candidates:
        if s in avail:
            return s
    return None

